# Concept map areas: the Model step is split in two so each picture stays readable.
TREES_AND_GROUPS = {"decision_tree", "regression_tree", "ensemble", "voting", "bagging", "random_forest", "boosting",
                    "adaboost", "gradient_boosting", "xgboost", "stacking", "clustering", "anomaly_detection",
                    "association_rules", "kmeans", "hierarchical", "dbscan"}
def first_note(c):
    """The Note that teaches the Concept. A maths or statistics Concept (step 0) may first appear in an ML Note
    that uses it; its home is the maths or statistics Note (200 to 999)."""
    if not c["videos"]:
        return 0
    maths = [v for v in c["videos"] if 200 <= v < 1000]
    return min(maths) if c["step"] == 0 and maths else min(c["videos"])


def ml(c):  # ML playlist Concepts; maths, statistics and deep learning get their own areas
    return first_note(c) < 200


# Maths and statistics Notes interleave topics in their numbering, so each topic lists its Note ranges.
MATHS_TOPICS = {"descriptive": [(200, 263), (270, 271), (560, 561)], "probability": [(330, 342)],
                "inference": [(271, 303), (570, 573)],
                "linear_algebra": [(350, 364), (440, 441), (490, 531), (580, 581)],
                "calculus": [(590, 630)], "likelihood": [(630, 650)]}


def maths_topic(c):
    v = first_note(c)
    return next((t for t, ranges in MATHS_TOPICS.items() if any(a <= v < b for a, b in ranges)), None)


AREAS = [("foundations", "Foundations and framing", lambda c: ml(c) and c["step"] <= 1),
         ("data", "Getting, understanding and cleaning data", lambda c: ml(c) and 2 <= c["step"] <= 4),
         ("features", "Features, dimensions and splitting", lambda c: ml(c) and 5 <= c["step"] <= 7),
         ("models_1", "Models: regression, classification and gradient descent",
          lambda c: ml(c) and c["step"] == 8 and c["id"] not in TREES_AND_GROUPS),
         ("models_2", "Models: trees, ensembles and clustering",
          lambda c: ml(c) and c["step"] == 8 and c["id"] in TREES_AND_GROUPS),
         ("production", "Evaluating, tuning and production", lambda c: ml(c) and c["step"] >= 9),
         ("descriptive", "Descriptive statistics and distributions", lambda c: maths_topic(c) == "descriptive"),
         ("probability", "Probability", lambda c: maths_topic(c) == "probability"),
         ("inference", "Sampling, inference and hypothesis tests", lambda c: maths_topic(c) == "inference"),
         ("linear_algebra", "Linear algebra", lambda c: maths_topic(c) == "linear_algebra"),
         ("calculus", "Calculus and optimisation", lambda c: maths_topic(c) == "calculus"),
         ("likelihood", "Likelihood, MLE and mixture models", lambda c: maths_topic(c) == "likelihood"),
         ("dl_basics", "Deep learning: perceptron to backpropagation", lambda c: 1000 <= first_note(c) < 1020),
         ("dl_training", "Deep learning: training better networks", lambda c: 1020 <= first_note(c) < 1032),
         ("dl_optimizers", "Deep learning: optimizers", lambda c: 1032 <= first_note(c) < 1040),
         ("dl_cnn", "Deep learning: convolutional networks", lambda c: 1040 <= first_note(c) < 1055),
         ("dl_rnn", "Deep learning: recurrent networks", lambda c: 1055 <= first_note(c) < 1067),
         ("dl_transformers", "Deep learning: LLMs, attention and transformers", lambda c: first_note(c) >= 1067)]


def validate():
    errors = []
    for link in LINKS:
        for end in (link["a"], link["b"]):
            if end not in CONCEPTS:
                errors.append(f"unknown concept {end!r} in link {link}")
        if link["type"] not in LINK_TYPES:
            errors.append(f"unknown link type in {link}")
        if link["status"] not in ("draft", "confirmed"):
            errors.append(f"bad status in {link}")
    for c in CONCEPTS.values():
        extra = set(c) - {"id", "name", "step", "videos", "status"}
        if extra:
            errors.append(f"unexpected keys {extra} in {c['id']} (a name with a comma must be quoted)")
        if c["step"] not in STEPS:
            errors.append(f"bad step for {c['id']}")
        if c["status"] not in ("draft", "confirmed"):
            errors.append(f"bad status for {c['id']}")
    if errors:
        raise SystemExit("concepts.yaml has errors:\n" + "\n".join(errors))


def note_ref(video, md_dir):
    """'Note 7' with a link if written, else 'Video 7 (coming)'."""
    if video in NOTES:
        return f"[Note {video}]({md_dir}{NOTES[video]}/note.md)"
    return f"Note {video}, coming"


# ---------------------------------------------------------------- Where this fits

def neighbours(video):
    """Concepts this Video builds on, leads to and is compared with, each with the Video that teaches it."""
    own = {cid for cid, c in CONCEPTS.items() if video in c["videos"]}
    before, after, compare = {}, {}, {}

    def first_video(cid, earlier):
        vids = [v for v in CONCEPTS[cid]["videos"] if (v < video if earlier else v > video)]
        return (max(vids) if earlier else min(vids)) if vids else None

    for link in LINKS:
        a, t, b = link["a"], link["type"], link["b"]
        for mine, other, mine_is_a in ((a, b, True), (b, a, False)):
            if mine not in own or other in own:
                continue
            if t == "compared with":
                v = first_video(other, True) or first_video(other, False)
                if v:
                    compare[other] = v
                continue
            # needs / is a kind of: a builds on b.  fixes: b (the problem) comes first.  used in: a comes first.
            other_first = (t in ("needs", "is a kind of", "fixes")) == mine_is_a
            v = first_video(other, other_first)
            if v:
                (before if other_first else after)[other] = v
    return own, before, after, compare


def pipeline_strip(steps_here):
    """TikZ: the 14 Pipeline map steps in two rows, with this Note's steps highlighted."""
    cells = []
    for s, name in SHORT.items():
        x, y = (s % 7) * 2.15, -(s // 7) * 0.85
        on = s in steps_here
        colour = STEP_COLOUR[s].lstrip("#")
        style = (f"draw=c{s}, fill=c{s}!30, line width=1.6pt, font=\\scriptsize\\bfseries" if on
                 else "draw=cgrey!50, fill=white, text=cgrey!80, font=\\scriptsize")
        cells.append(f"  \\definecolor{{c{s}}}{{HTML}}{{{colour}}}\n"
                     f"  \\node[rounded corners=3pt, minimum width=2.0cm, minimum height=0.62cm, {style}] "
                     f"at ({x:.2f},{y:.2f}) {{{s} {name}}};")
    return ("\\documentclass[tikz,border=4pt]{standalone}\n\\input{../../tools/tikz-style.tex}\n"
            "\\begin{document}\n\\begin{tikzpicture}\n" + "\n".join(cells) + "\n\\end{tikzpicture}\n\\end{document}\n")


def concept_list(items, md_dir, limit=6):
    ranked = sorted(items.items(), key=lambda kv: (CONCEPTS[kv[0]]["status"] != "confirmed", kv[1]))[:limit]
    return "; ".join(f"{CONCEPTS[cid]['name']} ({note_ref(v, md_dir)})" for cid, v in ranked)


def where_block(video):
    own, before, after, compare = neighbours(video)
    steps_here = sorted({CONCEPTS[c]["step"] for c in own})
    lines = [BEGIN,
             "> **Where this fits:** Pipeline map " + ("step " if len(steps_here) == 1 else "steps ")
             + ", ".join(f"{s} ({STEPS[s]})" for s in steps_here) + ". See the [Course map](../01-course-map/note.md).",
             ">", "> ![](images/where_this_fits.png)", ">"]
    for label, items in (("Builds on", before), ("Leads to", after), ("Compare with", compare)):
        if items:
            lines.append(f"> - **{label}:** {concept_list(items, '../')}.")
    lines.append(END)
    return "\n".join(lines), steps_here


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def note_tags(video):
    """Obsidian tags for a Note: its areas, pipeline steps and the Concepts it teaches, all from concepts.yaml."""
    here = [c for c in CONCEPTS.values() if video in c["videos"]]
    areas = sorted({a for a, _, member in AREAS for c in here if member(c)})
    steps = sorted({c["step"] for c in here})
    subject = ("deep-learning" if video >= 1000 else "ml" if video < 200
               else "statistics" if maths_topic({"videos": [video], "step": 0}) in ("descriptive", "probability", "inference")
               else "maths")
    return ([f"subject/{subject}"] + [f"area/{slug(a)}" for a in areas] + [f"step/{slug(SHORT[s])}" for s in steps]
            + sorted(f"concept/{slug(c['id'])}" for c in here))


def set_tags(text, video):
    """Write the tags line into the front matter, replacing an old one; the PDF build ignores it."""
    tags = note_tags(video)
    text = re.sub(r"\ntags: \[[^\]]*\]", "", text, count=1)
    if tags and text.startswith("---\n"):
        end = text.index("\n---", 4)
        text = text[:end] + f"\ntags: [{', '.join(tags)}]" + text[end:]
    return text


def update_note(video):
    folder = ROOT / NOTES[video]
    note = folder / "note.md"
    text = set_tags(note.read_text(), video)
    block, steps_here = where_block(video)
    (folder / "images").mkdir(exist_ok=True)
    (folder / "images" / "where_this_fits.tex").write_text(pipeline_strip(steps_here))
    text = re.sub(r"\n\*\*Prerequisites:\*\*[^\n]*\n", "\n", text)                    # replaced by the box
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        first = text.index("\n## ")
        text = text[:first] + "\n" + block + "\n" + text[first:]
    note.write_text(text)


