def neighbours(video):
    """Concepts this Video builds on, leads to and is compared with, each with the Video that teaches it."""
    own = {cid for cid, c in CONCEPTS.items() if video in c["videos"]}
    before, after, compare = {}, {}, {}

    def first_video(cid, earlier):
        vids = [v for v in CONCEPTS[cid]["videos"] if (v < video if earlier else v > video)]
        return (max(vids) if earlier else min(vids)) if vids else None

    for link in LINKS:
        a, t, b = link["a"], link["type"], link["b"]
        for mine, other, mine_is_a in ((a, b, True), (b, a, False)):
            if mine not in own or other in own:
                continue
            if t == "compared with":
                v = first_video(other, True) or first_video(other, False)
                if v:
                    compare[other] = v
                continue
            # needs / is a kind of: a builds on b.  fixes: b (the problem) comes first.  used in: a comes first.
            other_first = (t in ("needs", "is a kind of", "fixes")) == mine_is_a
            # "Builds on" points at the Note that teaches the concept (its owner), not merely the nearest
            # earlier Note that uses it; "Leads to" points at the next Note that uses it
            v = first_note(CONCEPTS[other]) if other_first else first_video(other, False)
            if v and v != video:
                (before if other_first else after)[other] = v
    return own, before, after, compare


def pipeline_strip(steps_here):
    """TikZ: the 14 Pipeline map steps in two rows, with this Note's steps highlighted."""
    cells = []
    for s, name in SHORT.items():
        x, y = (s % 7) * 2.15, -(s // 7) * 0.85
        on = s in steps_here
        colour = STEP_COLOUR[s].lstrip("#")
        style = (f"draw=c{s}, fill=c{s}!30, line width=1.6pt, font=\\scriptsize\\bfseries" if on
                 else "draw=cgrey!50, fill=white, text=cgrey!80, font=\\scriptsize")
        cells.append(f"  \\definecolor{{c{s}}}{{HTML}}{{{colour}}}\n"
                     f"  \\node[rounded corners=3pt, minimum width=2.0cm, minimum height=0.62cm, {style}] "
                     f"at ({x:.2f},{y:.2f}) {{{s} {name}}};")
    return ("\\documentclass[tikz,border=4pt]{standalone}\n\\input{../../../../tools/tikz-style.tex}\n"
            "\\begin{document}\n\\begin{tikzpicture}\n" + "\n".join(cells) + "\n\\end{tikzpicture}\n\\end{document}\n")


def section_of(note_md, name):
    """Anchor of the section that teaches `name` in a Note: the heading above its first bold mention, else above its
    first plain mention, else "" (NOTE-RULES §17). Headings with maths are skipped (unreliable anchors)."""
    if not note_md.exists():
        return ""
    lines = note_md.read_text(encoding="utf-8").splitlines()
    lines = lines[next((i for i, l in enumerate(lines) if l.startswith("<!-- /where-this-fits")), 0):]
    base = re.sub(r"\s*\([^)]*\)", "", name).strip()                 # "Deep (stacked) RNNs" -> "Deep RNNs"
    keys = [name, base] + re.findall(r"\(([^)]*)\)", name) + re.split(r",| and ", base)
    keys = [k.strip().lower() for k in keys if len(k.strip()) > 3]
    keys += [k[:-1] for k in keys if k.endswith("s")]                  # "bidirectional rnns" -> "...rnn"
    for line in lines:                                  # the earliest heading that names it wins (it teaches it)
        m = re.match(r"^#{2,6}\s+(.*?)\s*$", line)
        h = m.group(1).lower() if m else ""
        if h and "$" not in h and any(k in h for k in keys) \
                and not re.match(r"[\d.]+ (overview|summary|sources|key terms)", h):
            return "#" + anchor(m.group(1))
    first = ""
    for bold in (True, False):                     # a bold (defining) mention of any name form beats a plain one
        for key in keys:
            heading = ""
            for line in lines:
                m = re.match(r"^#{2,6}\s+(.*?)\s*$", line)
                if m:
                    heading = m.group(1) if "$" not in m.group(1) else heading
                    first = first or heading
                    continue
                low = line.lower()
                if heading and ((f"**{key}**" in low) if bold else key in low) and not line.startswith("!["):
                    return "#" + anchor(heading)
    return "#" + anchor(first) if first else ""      # the whole Note is about it: its Overview


def concept_link(cid, video, md_dir):
    """[Concept name](Note.md#section that teaches it): the idea is the link text, not "Note XX-NNN" (§17)."""
    name = CONCEPTS[cid]["name"]
    if video not in NOTES:
        return f"{name} (coming)"
    rel = f"{NOTES[video]}/{Path(NOTES[video]).name}.md"
    return f"[{name}]({md_dir}{rel}{section_of(ROOT / rel, name)})"


def concept_list(items, md_dir, limit=6):
    ranked = sorted(items.items(), key=lambda kv: (CONCEPTS[kv[0]]["status"] != "confirmed", kv[1]))[:limit]
    return "; ".join(concept_link(cid, v, md_dir) for cid, v in ranked)


def where_block(video):
    own, before, after, compare = neighbours(video)
    steps_here = sorted({CONCEPTS[c]["step"] for c in own})
    lines = [BEGIN,
             "> **Where this fits:** Pipeline map " + ("step " if len(steps_here) == 1 else "steps ")
             + ", ".join(f"{s} ({STEPS[s]})" for s in steps_here) + ". See the [Course map](../../../00-course-map/00-course-map.md).",
             ">", "> ![](images/where_this_fits.png)", ">"]
    for label, items in (("Builds on", before), ("Leads to", after), ("Compare with", compare)):
        if items:
            lines.append(f"> - **{label}:** {concept_list(items, '../../../')}.")
    lines.append(END)
    return "\n".join(lines), steps_here


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def note_tags(video):
    """Obsidian tags for a Note: its areas, pipeline steps and the Concepts it teaches, all from concepts.yaml."""
    here = [c for c in CONCEPTS.values() if video in c["videos"]]
    areas = sorted({a for a, _, member in AREAS for c in here if member(c)})
    steps = sorted({c["step"] for c in here})
    subj = {"DL": "deep-learning", "ML": "ml"}.get(subject(video)) or (
        "statistics" if maths_topic({"videos": [video], "step": 0}) in ("descriptive", "probability", "inference")
        else "maths")
    return ([f"subject/{subj}"] + [f"area/{slug(a)}" for a in areas] + [f"step/{slug(SHORT[s])}" for s in steps]
            + sorted(f"concept/{slug(c['id'])}" for c in here))


def set_tags(text, video):
    """Write the tags line into the front matter, replacing an old one; the PDF build ignores it."""
    tags = note_tags(video)
    text = re.sub(r"\ntags: \[[^\]]*\]", "", text, count=1)
    if tags and text.startswith("---\n"):
        end = text.index("\n---", 4)
        text = text[:end] + f"\ntags: [{', '.join(tags)}]" + text[end:]
    return text


def update_note(video):
    folder = ROOT / NOTES[video]
    note = note_file(video)
    text = set_tags(note.read_text(), video)
    block, steps_here = where_block(video)
    (folder / "images").mkdir(exist_ok=True)
    (folder / "images" / "where_this_fits.tex").write_text(pipeline_strip(steps_here))
    text = re.sub(r"\n\*\*Prerequisites:\*\*[^\n]*\n", "\n", text)                    # replaced by the box
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        first = text.index("\n## ")
        text = text[:first] + "\n" + block + "\n" + text[first:]
    note.write_text(text)


