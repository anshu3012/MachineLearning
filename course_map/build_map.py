def pipeline_overview():
    """TikZ: the 14 steps as a snake with counts, and a loop between Understand and Clean."""
    nodes, arrows = [], []
    for s, name in STEPS.items():
        row, col = divmod(s, 5)
        x = (col if row % 2 == 0 else 4 - col) * 3.6
        y = -row * 2.3
        here = [c for c in CONCEPTS.values() if c["step"] == s]
        done = sum(c["status"] == "confirmed" for c in here)
        colour = STEP_COLOUR[s].lstrip("#")
        nodes.append(f"  \\definecolor{{c{s}}}{{HTML}}{{{colour}}}\n"
                     f"  \\node[box=c{s}, minimum width=3.0cm, minimum height=1.35cm] (s{s}) at ({x:.1f},{y:.1f}) "
                     f"{{\\textbf{{{s}. {name}}}\\\\{{\\small {done} of {len(here)} confirmed}}}};")
        if s:
            arrows.append(f"  \\draw[arrow] (s{s - 1}) -- (s{s});")
    loop = "  \\draw[arrow, draw=cred, dashed] (s4.north) to[bend right=35] node[above, font=\\scriptsize, text=cred] {back and forth} (s3.north);"
    return ("\\documentclass[tikz,border=8pt]{standalone}\n\\input{../../tools/tikz-style.tex}\n"
            "\\begin{document}\n\\begin{tikzpicture}\n" + "\n".join(nodes + arrows) + "\n" + loop
            + "\n\\end{tikzpicture}\n\\end{document}\n")


def note_title(video):
    """The Note's own title from its front matter; 'Note N, coming' for Notes not written yet."""
    if video not in NOTES:
        return f"Note {video}, coming"
    m = re.search(r'^title:\s*"(.*)"', note_file(video).read_text(), re.M)
    return f"{label(video)} " + (m.group(1) if m else Path(NOTES[video]).name)


